export function findCountryPortal(nameOrAlias) {
  if (!nameOrAlias || typeof nameOrAlias !== 'string') return null;
  const target = nameOrAlias.trim().toLowerCase();
  return countryPortals.find(p =>
    p.country.toLowerCase() === target ||
    p.aliases.some(a => {
      try {
        return new RegExp(a, 'i').test(target);
      } catch {
        return a.toLowerCase() === target;
      }
    })
  ) || null;
}
